export type LocaleMessageKey = (typeof LOCALE_MESSAGE_KEYS)[number]

export type LocaleMessages = Record<LocaleMessageKey, string>

export type LocaleMessagesValidation = { ok: true } | { ok: false; errors: string[] }

/** 校验插件或内置包是否包含全部词条且为非空字符串 */
export function validateLocaleMessages(raw: unknown): LocaleMessagesValidation {
  if (raw === null || typeof raw !== 'object' || Array.isArray(raw)) {
    return { ok: false, errors: ['messages 必须是对象'] }
  }
  const obj = raw as Record<string, unknown>
  const errors: string[] = []
  for (const key of LOCALE_MESSAGE_KEYS) {
    const v = obj[key]
    if (typeof v !== 'string') {
      errors.push(`缺少或类型错误: ${key}`)
      continue
    }
    if (!v.trim()) {
      errors.push(`词条为空: ${key}`)
    }
  }
  if (errors.length) return { ok: false, errors }
  return { ok: true }
}

export function isCompleteLocaleMessages(raw: unknown): raw is LocaleMessages {
  return validateLocaleMessages(raw).ok === true
}
